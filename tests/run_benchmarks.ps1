<#
Builds the engine and runs it against the tests/*.txt files generated by
generate_tests.ps1, reporting wall-clock time and peak working-set memory
for each -- the same two axes the judge screenshot (Total memory / Time)
graded on -- and flags any test that breaks the given time/memory limits.

This does NOT reproduce the judge's exact memory-accounting method (that
table's "Total/Static/Stack memory" columns come from whatever sandboxed
judging tool graded the original submission, which we don't have). Treat
the numbers here as a LOCAL, RELATIVE signal: is this test still fast/
lean after a change, and does the LARGE_GRAPH branch actually kick in and
stay fast for the near-threshold and over-threshold buckets.

Usage:
    .\run_benchmarks.ps1                          # generate tests if missing, build, run, check limits
    .\run_benchmarks.ps1 -SkipBuild                # reuse existing exe
    .\run_benchmarks.ps1 -TimeLimitSeconds 10 -MemoryLimitKB 65536
    .\run_benchmarks.ps1 -Regenerate               # force re-generating tests/*.txt first
#>

param(
    [switch]$SkipBuild,
    [switch]$Regenerate,
    [double]$TimeLimitSeconds = 15.0,
    [double]$MemoryLimitKB = 65536.0
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$exePath = Join-Path $root "engine.exe"

if ($Regenerate -or -not (Get-ChildItem -Path $PSScriptRoot -Filter "*.txt" -ErrorAction SilentlyContinue)) {
    Write-Host "No test files found (or -Regenerate given) -- generating..."
    & (Join-Path $PSScriptRoot "generate_tests.ps1")
    Write-Host ""
}

if (-not $SkipBuild) {
    . (Join-Path $root "msvc_env.ps1")
    Import-VsDevEnvironment
    Write-Host "Building..."
    Push-Location $root
    try {
        $sources = "main.cpp", "graph.cpp", "vertex.cpp", "node.cpp", "list.cpp", "unionfind.cpp", "degreesequence.cpp"
        & cl.exe /nologo /O2 /EHsc /std:c++17 "/Fe:$exePath" @sources 2>&1 | Out-Null
        if (-not (Test-Path $exePath)) {
            throw "Build failed -- exe not produced. Run cl.exe manually to see errors."
        }
    }
    finally {
        Pop-Location
    }
    Write-Host "Built $exePath"
    Write-Host ""
}
elseif (-not (Test-Path $exePath)) {
    throw "No existing exe at $exePath -- run without -SkipBuild first."
}

$testFiles = Get-ChildItem -Path $PSScriptRoot -Filter "*.txt" | Sort-Object Name
if ($testFiles.Count -eq 0) {
    throw "No test files found in $PSScriptRoot even after generation -- check generate_tests.ps1."
}

$results = @()
$stdoutDir = Join-Path $PSScriptRoot "_stdout"
New-Item -ItemType Directory -Force -Path $stdoutDir | Out-Null

foreach ($f in $testFiles) {
    $stdoutFile = Join-Path $stdoutDir "$($f.BaseName).out.txt"

    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $proc = Start-Process -FilePath $exePath -RedirectStandardInput $f.FullName `
        -RedirectStandardOutput $stdoutFile -NoNewWindow -PassThru
    [void]$proc.Handle  # forces a real handle now, else ExitCode reads back null later

    $peakKb = 0
    while (-not $proc.HasExited) {
        try {
            $proc.Refresh()
            $peakKb = [Math]::Max($peakKb, [Math]::Round($proc.PeakWorkingSet64 / 1KB, 0))
        }
        catch { }
        Start-Sleep -Milliseconds 5
    }
    $proc.WaitForExit()
    $sw.Stop()

    $elapsedSec = [Math]::Round($sw.Elapsed.TotalSeconds, 3)
    $timeOver = $elapsedSec -gt $TimeLimitSeconds
    $memOver = $peakKb -gt $MemoryLimitKB
    $crashed = $proc.ExitCode -ne 0

    $status = "PASS"
    if ($crashed) { $status = "CRASH" }
    elseif ($timeOver -and $memOver) { $status = "TIME+MEM LIMIT" }
    elseif ($timeOver) { $status = "TIME LIMIT" }
    elseif ($memOver) { $status = "MEM LIMIT" }

    $results += [PSCustomObject]@{
        Test            = $f.BaseName
        "Time [s]"      = $elapsedSec
        "Peak Mem [KB]" = $peakKb
        "Exit Code"     = [string]$proc.ExitCode
        Status          = $status
    }
}

$results | Format-Table -AutoSize

$failed = @($results | Where-Object { $_.Status -ne "PASS" })
Write-Host ""
if ($failed) {
    Write-Host "$($failed.Count) of $($results.Count) test(s) FAILED (limits: $TimeLimitSeconds s / $MemoryLimitKB KB):" -ForegroundColor Yellow
    $failed | ForEach-Object { Write-Host "  - $($_.Test): $($_.Status) (time=$($_.'Time [s]')s, mem=$($_.'Peak Mem [KB]')KB, exit=$($_.'Exit Code'))" -ForegroundColor Yellow }
    exit 1
}
else {
    Write-Host "All $($results.Count) tests passed within $TimeLimitSeconds s / $MemoryLimitKB KB." -ForegroundColor Green
    exit 0
}
